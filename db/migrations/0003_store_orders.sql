-- Orders placed through our sandbox merchant store (/store). Independent of the standing-order tables.

CREATE TABLE store_orders (
  id              uuid PRIMARY KEY, -- generated by the app and sent to PayPal as reference_id
  product_id      text NOT NULL,
  amount_cents    integer NOT NULL CHECK (amount_cents > 0),
  paypal_order_id text NOT NULL UNIQUE,
  capture_id      text,
  status          text NOT NULL DEFAULT 'created'
                    CHECK (status IN ('created', 'approved', 'captured', 'cancelled', 'failed')),
  created_at      timestamptz NOT NULL DEFAULT now(),
  captured_at     timestamptz
);
